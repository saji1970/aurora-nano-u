#!/usr/bin/env python3
"""Make functional Verilog models for the IHP SG13G2 cells a netlist uses,
from the liberty file's own 'function' strings (for gate-level simulation
with simulators that lack the timing features the vendor models need)."""
import re, sys

lib, netlist, out = sys.argv[1:4]
used = set(re.findall(r'^\s*(sg13g2_\w+)\s+\S+\s*\(', open(netlist).read(), re.M))
text = open(lib).read()

def expr(f):
    f = f.replace('"', '').strip()
    f = re.sub(r'(\w)\s+(?=[\w!(])', r'\1 & ', f)      # implicit AND (space)
    f = f.replace('+', '|').replace('*', '&').replace('!', '~')
    return f

models = []
for m in re.finditer(r'\n\s*cell\s*\(\s*"?(sg13g2_\w+)"?\s*\)\s*\{', text):
    name = m.group(1)
    if name not in used:
        continue
    body_start = m.end(); depth = 1; i = body_start
    while depth:
        if text[i] == '{': depth += 1
        elif text[i] == '}': depth -= 1
        i += 1
    body = text[body_start:i]
    pins = []
    for pm in re.finditer(r'\bpin\s*\(\s*"?(\w+)"?\s*\)\s*\{', body):
        d = 1; k = pm.end()
        while d:
            if body[k] == '{': d += 1
            elif body[k] == '}': d -= 1
            k += 1
        pins.append((pm.group(1), body[pm.end():k]))
    ins = [p for p, b in pins if re.search(r'direction\s*:\s*"?input', b)]
    outs = [(p, re.search(r'function\s*:\s*("[^"]*")', b)) for p, b in pins if re.search(r'direction\s*:\s*"?output', b)]
    ports = [p for p, _ in outs] + ins
    lines = [f"module {name} ({', '.join(ports)});"]
    lines += [f"  input {p};" for p in ins]
    if 'ff (' in body or 'ff(' in body:
        # sg13g2_dfrbp*: async active-low reset flip-flop
        assert set(ins) >= {'CLK', 'D', 'RESET_B'}, name
        lines += ["  reg q;", "  always @(posedge CLK or negedge RESET_B) q <= !RESET_B ? 1'b0 : D;"]
        for p, f in outs:
            lines += [f"  output {p};", f"  assign {p} = {'~q' if p.endswith('_N') else 'q'};"]
    else:
        for p, f in outs:
            lines += [f"  output {p};", f"  assign {p} = {expr(f.group(1)) if f else '1bx'};"]
    lines.append("endmodule\n")
    models.append("\n".join(lines))

missing = used - {re.match(r'module (\w+)', m).group(1) for m in models}
assert not missing, missing
open(out, 'w').write("// generated by lib2models.py\n`timescale 1ns/1ps\n" + "\n".join(models))
print(f"{len(models)} cell models written")
